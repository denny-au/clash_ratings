// Builds public/planner-model.js (the upgrade times the Planner needs) from the open-source
// "clash-of-clans-data" package. Run it again after the game gets a new Town Hall or balance change:
//
//   npm install --no-save clash-of-clans-data
//   node tools/build-planner-model.js
//
// Optional: pass the package's data folder as the first argument.
'use strict';
const fs = require('fs');
const path = require('path');

const dataDir = path.resolve(process.argv[2] || path.join(__dirname, '..', 'node_modules', 'clash-of-clans-data', 'data', 'home'));
const out = path.join(__dirname, '..', 'public', 'planner-model.js');

const secs = (t) => (t ? (t.days || 0) * 86400 + (t.hours || 0) * 3600 + (t.minutes || 0) * 60 + (t.seconds || 0) : 0);
const read = (rel) => JSON.parse(fs.readFileSync(path.join(dataDir, rel), 'utf8'));
const list = (dir) => fs.readdirSync(path.join(dataDir, dir)).filter((f) => f.endsWith('.json')).map((f) => dir + '/' + f);

const model = {
  built: new Date().toISOString().slice(0, 10),
  // b: things a builder upgrades. t[i] = seconds to reach level i+1, r[i] = Town Hall that level needs, c[th] = how many you may own
  b: {}, h: {}, l: {}, p: {},
  hall: [], // Town Hall each Hero Hall level needs (index 0 = Hero Hall level 1)
  th: [],   // seconds to upgrade TO Town Hall level i+1
};

// buildings (everything a builder upgrades except walls and traps)
const buildingDirs = ['army-buildings', 'defenses', 'resource-buildings', 'other', 'guardians'];
buildingDirs.forEach((dir) => {
  list(dir).forEach((rel) => {
    const d = read(rel);
    if (!d.dataId || !Array.isArray(d.levels) || !d.levels.length || !d.levels[0].buildTime) return;
    const c = [0];
    (d.availablePerTownHall || []).forEach((a) => { c[a.townHallLevel] = a.countAfterMerges != null ? -1 : a.count; });
    model.b[d.dataId] = {
      n: d.name,
      t: d.levels.map((l) => secs(l.buildTime)),
      r: d.levels.map((l) => l.townHallRequired || 1),
      c: Array.from({ length: 19 }, (_, i) => (c[i] == null ? 0 : c[i])),
      cat: dir,
    };
  });
});
const th = read('town-hall/town-hall.json');
model.th = th.levels.map((l) => secs(l.buildTime));
model.hall = read('army-buildings/hero-hall.json').levels.map((l) => l.townHallRequired);

// heroes (a builder), pets (their own slot), troops / spells / siege machines (the lab)
list('heroes').forEach((rel) => {
  const d = read(rel);
  model.h[d.dataId] = { n: d.name, t: d.levels.map((l) => secs(l.upgradeTime)), r: d.levels.map((l) => l.heroHallLevelRequired || 1) };
});
list('pets').forEach((rel) => {
  const d = read(rel);
  model.p[d.dataId] = { n: d.name, t: d.levels.map((l) => secs(l.upgradeTime)), r: d.levels.map((l) => l.townHallRequired || 1) };
});
['troops', 'spells', 'siege-machines'].forEach((dir) => {
  list(dir).forEach((rel) => {
    const d = read(rel);
    if (!d.dataId) return;
    model.l[d.dataId] = { n: d.name, t: d.levels.map((l) => secs(l.researchTime)), r: d.levels.map((l) => l.townHallRequired || 1) };
  });
});

const body = JSON.stringify(model);
fs.writeFileSync(out, '// Generated by tools/build-planner-model.js from the clash-of-clans-data package. Do not edit by hand.\nwindow.CR_MODEL = ' + body + ';\n');
console.log('wrote', out, (body.length / 1024).toFixed(1) + ' KB');
